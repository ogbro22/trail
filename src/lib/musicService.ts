// Jamendo Client ID (Public Free API Key for non-commercial music applications)
const JAMENDO_CLIENT_ID = 'c701bc93';

export async function searchJamendoTracks(query: string): Promise<Track[]> {
  try {
    const res = await fetch(
      `https://api.jamendo.com/v3.0/tracks/?client_id=${JAMENDO_CLIENT_ID}&format=json&limit=15&search=${encodeURIComponent(
        query
      )}&include=musicinfo&audioformat=mp32`
    );
    if (!res.ok) return [];
    const data = await res.json();
    if (!data.results) return [];

    return data.results.map((item: any) => ({
      id: `jamendo-${item.id}`,
      title: item.name || 'Unknown Title',
      artist: item.artist_name || 'Unknown Artist',
      album: item.album_name || 'Jamendo Single',
      duration: item.duration || 180,
      audioUrl: item.audio || item.audiodownload,
      coverUrl: item.image || item.album_image || 'https://images.unsplash.com/photo-1470225620780-dba8ba36b745?q=80&w=800&auto=format&fit=crop',
      genre: item.musicinfo?.tags?.genres?.[0] || 'Pop / Rock',
      source: 'Jamendo' as const,
      plainLyrics: item.musicinfo?.lyrics || `[00:05.00] Enjoy listening to ${item.name} by ${item.artist_name}\n[00:15.00] Streaming full high-quality audio track from Jamendo\n[00:30.00] ♪ (Instrumental harmony) ♪`,
      lyrics: generateFallbackLrc(item.name, item.artist_name, item.duration || 180)
    }));
  } catch (err) {
    console.error('Error fetching Jamendo tracks:', err);
    return [];
  }
}

export async function fetchAudiusTrendingTracks(): Promise<Track[]> {
  try {
    const res = await fetch('https://discoveryprovider.audius.co/v1/tracks/trending?app_name=SonoraPlayer&limit=15');
    if (!res.ok) return [];
    const data = await res.json();
    if (!data.data) return [];

    return data.data.map((item: any) => {
      const trackId = item.id;
      const streamUrl = `https://discoveryprovider.audius.co/v1/tracks/${trackId}/stream?app_name=SonoraPlayer`;
      return {
        id: `audius-${trackId}`,
        title: item.title || 'Audius Track',
        artist: item.user?.name || item.user?.handle || 'Audius Artist',
        album: 'Audius Stream',
        duration: item.duration || 180,
        audioUrl: streamUrl,
        coverUrl: item.artwork?.['1000x1000'] || item.artwork?.['480x480'] || 'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?q=80&w=800&auto=format&fit=crop',
        genre: item.genre || 'Electronic',
        source: 'Audius' as const,
        lyrics: generateFallbackLrc(item.title, item.user?.name || 'Artist', item.duration || 180)
      };
    });
  } catch (err) {
    console.error('Error fetching Audius tracks:', err);
    return [];
  }
}

function generateFallbackLrc(title: string, artist: string, duration: number) {
  const steps = 8;
  const interval = Math.max(10, Math.floor(duration / steps));
  const lines = [
    { time: 0, text: `♪ Starting "${title}" by ${artist} ♪` },
    { time: interval, text: `Feel the rhythm and beat of ${artist}` },
    { time: interval * 2, text: `Full length high quality audio streaming on Sonora` },
    { time: interval * 3, text: `♪ (Musical bridge & harmony) ♪` },
    { time: interval * 4, text: `Music brings inspiration to your soul` },
    { time: interval * 5, text: `♪ (Instrumental solo performance) ♪` },
    { time: interval * 6, text: `Thank you for listening to ${title}` },
    { time: Math.max(0, duration - 10), text: `♪ (Fade out) ♪` }
  ];
  return lines;
}
